DATA_FILE = r'C:\Users\rosef\Documents\GitHub\아신산업 과제\KDT14-work\work_04_김병욱\남북한발전전력량.xlsx'
# ==============================================
# [문제 1] 파일 읽기 및 출력
# ==============================================
df = pd.read_excel(DATA_FILE)
print(df, "\n")


# ==============================================
# [문제 2] 기본 정보 확인
# ==============================================
print(f"1. 행과 열: {df.shape}\n")
print(f"2. 컬럼명: {df.columns.tolist()}\n")
print(f"3. 인덱스: {df.index}\n")
print(f"4. 자료형:\n{df.dtypes}\n")
print(f"5. 앞 5행:\n{df.head()}\n")


# ==============================================
# [문제 3] 컬럼명 "구분"으로 변경
# ==============================================
df.rename(columns={df.columns[0]: "구분"}, inplace=True)
print(f"변경 후 컬럼명: {df.columns.tolist()}\n")


# ==============================================
# [문제 4] 결측치 확인
# ==============================================
print(f"컬럼별 결측치 개수:\n{df.isna().sum()}\n")
print(f"전체 결측치 총합: {df.isna().sum().sum()}\n")


# ==============================================
# [문제 5] 구분 컬럼 결측치 채우기 (ffill)
# ==============================================
print(f"처리 전 결측치 개수: {df['구분'].isna().sum()}\n")
df['구분'] = df['구분'].ffill()
print(f"처리 후 결측치 개수: {df['구분'].isna().sum()}\n")


# ==============================================
# [문제 6] 중복값 확인
# ==============================================
print(f"행별 중복 여부:\n{df.duplicated()}\n")
print(f"중복 행 총 개수: {df.duplicated().sum()}\n")


# ==============================================
# [문제 7] 특정 컬럼만 선택하여 df_basic 생성
# ==============================================
df_basic = df[['구분', '발전 전력별', '1990', '2000', '2010', '2016']].copy()
print(df_basic.head(), "\n")


# ==============================================
# [문제 8] 앞쪽 5개 행, 마지막 3개 행 출력
# ==============================================
print("앞쪽 5개 행:\n", df.head(5), "\n")
print("마지막 3개 행:\n", df.tail(3), "\n")


# ==============================================
# [문제 9] 0~3번 행 선택 및 특정 컬럼 출력
# ==============================================
# 조건식 없이 iloc와 컬럼 리스트 활용
result_9 = df.iloc[0:4][["구분", "발전 전력별", "1990", "2016"]]
print(result_9, "\n")


# ==============================================
# [문제 11] "발전 전력별" 인덱스 설정
# ==============================================
df_power = df.set_index('발전 전력별')
print("변경된 인덱스:\n", df_power.index, "\n")


# ==============================================
# [문제 12] 인덱스를 다시 컬럼으로 되돌리기
# ==============================================
df_power = df_power.reset_index()
print(df_power.head(), "\n")


# ==============================================
# [문제 13] 1990년~2016년 컬럼만 선택하여 df_years 저장
# ==============================================
df_years = df.loc[:, '1990':'2016']
print(df_years.head(), "\n")


# ==============================================
# [문제 14] df_years 기초 통계 정보 확인
# ==============================================
print(df_years.describe(), "\n")


# ==============================================
# [문제 15] 연도별 평균값 구하기
# ==============================================
print("연도별 평균 발전량:\n", df_years.mean(), "\n")


# ==============================================
# [문제 16] 각 행의 평균 구하여 "평균" 컬럼 추가
# ==============================================
# '-' 등 문자열이 섞여있을 경우를 대비해 숫자로 변환 후 계산
df_years_num = df_years.apply(pd.to_numeric, errors='coerce')
df['평균'] = df_years_num.mean(axis=1)
print(df[['구분', '발전 전력별', '평균']].head(), "\n")


# ==============================================
# [문제 17] 최대값, 최소값 컬럼 추가
# ==============================================
df['최대값'] = df_years_num.max(axis=1)
df['최소값'] = df_years_num.min(axis=1)
print(df[['발전 전력별', '최대값', '최소값']].head(), "\n")


# ==============================================
# [문제 18] 1990_2016_변화량 컬럼 추가
# ==============================================
v1990 = pd.to_numeric(df['1990'], errors='coerce')
v2016 = pd.to_numeric(df['2016'], errors='coerce')
df['1990_2016_변화량'] = v2016 - v1990
print(df[['발전 전력별', '1990_2016_변화량']].head(), "\n")


# ==============================================
# [문제 19] 1990_2016_변화율 컬럼 추가
# ==============================================
df['1990_2016_변화율'] = (df['1990_2016_변화량'] / v1990) * 100
print(df[['발전 전력별', '1990_2016_변화율']].head(), "\n")


# ==============================================
# [문제 20] 2016년 컬럼에서 가장 큰 값
# ==============================================
print(f"2016년 최대값: {v2016.max()}\n")


# ==============================================
# [문제 21] 1990년 컬럼에서 가장 작은 값
# ==============================================
print(f"1990년 최소값: {v1990.min()}\n")


# ==============================================
# [문제 22] 2000년부터 2010년까지 컬럼 선택 출력
# ==============================================
print(df.loc[:, '2000':'2010'], "\n")


# ==============================================
# [문제 23] df 복사 및 특정 컬럼 삭제
# ==============================================
df_copy = df.copy()
df_copy.drop(columns=['평균', '최대값', '최소값'], inplace=True)
print("삭제 후 컬럼 목록:", df_copy.columns.tolist(), "\n")


# ==============================================
# [문제 24] 변화량 기준 내림차순 정렬
# ==============================================
df_sorted = df.sort_values(by='1990_2016_변화량', ascending=False)
print(df_sorted.head(), "\n")


# ==============================================
# [문제 25] 구분코드 추가 (남한: 1, 북한: 2)
# ==============================================
df['구분코드'] = df['구분'].apply(lambda x: 1 if x == '남한' else 2)
print(df[['구분', '구분코드']].head(), "\n")