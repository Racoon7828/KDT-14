result = y_df.query("Y2017 >= 100000")
result = result[['전출지별','전입지별','Y2017']]
result = result.sort_values(by='Y2017', ascending=False)
print(f"2017년 이동자수가 100000명 이상인 데이터 \n{result}\n")

