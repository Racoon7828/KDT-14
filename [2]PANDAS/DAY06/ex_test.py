# [주의사항]
# - 컬럼명이 숫자 형태이면 query()에서 사용하기 어려울 수 있습니다.
# - 필요한 경우 2017 컬럼명을 "Y2017"과 같이 변경한 후 query()를 사용하세요.
# ============================================================
y_df = pop_df.apply(pd.to_numeric, errors='ignore')
print(f" \n{y_df.dtypes}\n")
